"""kicad3d - electronic components (pin headers, JST/USB/barrel connectors,
buttons, LEDs, resistors, capacitors, chips, relays, battery holders,
sensors, ESP32 / Pico modules...) from the KiCad 3D model library,
installed into the user's own parts (user_parts.py).

SOURCE
    gitlab.com/kicad/libraries/kicad-packages3D at REVISION, CC BY-SA 4.0
    with KiCad's exception (LICENSE.md): a design that USES the models is
    not bound by share-alike; redistributing the models as a collection is.
    Prompt2Product ships no model, only the index, and downloads a model when
    the user installs it. The models are made by the KiCad library
    contributors (mostly generated by their CadQuery scripts); the index
    keeps the author the STEP header names.

    Only a CURATED list is offered: kicad3d_index.json, written by
    build_kicad3d_index.py, holds each model's path, git blob id and size
    (checked on download), its size MEASURED from its mesh, a picture drawn
    from the mesh (kicad3d_pictures/), and what we say about it.

INSTALL
    as shelf.install: download (HTTPS, blob id and size checked) -> mesh in
    a child freecadcmd -> user_parts.import_part(extra={"kicad3d": ...}).

The module offers the same functions as shelf.py, so shelf_dialog shows it.
"""
import json
import os
import re
import shutil
import tempfile
import urllib.parse

import shelf

HERE = os.path.dirname(os.path.abspath(__file__))
INDEX = os.path.join(HERE, "kicad3d_index.json")
PROJECT = "kicad/libraries/kicad-packages3D"
PROJECT_ID = 21604637                      # gitlab.com's id of PROJECT
REVISION = "afa6aab16f43a736cd062b8c853863e753653921"     # master, 3 Nov 2026
LICENCE = "CC BY-SA 4.0"
SOURCE = "the KiCad 3D model library (gitlab.com/kicad/libraries/kicad-packages3D)"
PREFIX = "kc_"

#: what shelf_dialog says for this source
TITLE = "Electronic components (KiCad)"
INTRO = ("Pin headers, connectors, buttons, LEDs, resistors, capacitors, chips, "
         "relays, battery holders, sensors and modules from the KiCad 3D model "
         "library, at their real sizes. An installed one joins your parts.")
SEARCH_HINT = "Search: pin header, JST, USB-C, LED, DIP-8, relay, 18650…"
CREDIT = "Models from the KiCad library, CC BY-SA 4.0 (designs that use them are yours)"

GROUPS = (("modules", "Modules"), ("connectors", "Connectors"),
          ("controls", "Buttons and switches"), ("lights", "LEDs and displays"),
          ("passives", "Resistors, capacitors, crystals"),
          ("chips", "Chips and transistors"), ("power", "Power and batteries"),
          ("sensors", "Sensors and sound"), ("relays", "Relays and heatsinks"))

ShelfError = shelf.ShelfError


def file_url(path, rev=REVISION):
    return "https://gitlab.com/%s/-/raw/%s/%s" % (PROJECT, rev, urllib.parse.quote(path))


def page_url(path, rev=REVISION):
    return "https://gitlab.com/%s/-/blob/%s/%s" % (PROJECT, rev, urllib.parse.quote(path))


def fetch(path, git_oid, size, dest, rev=REVISION):
    """Download `path` to dest, checked against its git blob id (and size
    when known); the problem as a ShelfError, nothing left behind."""
    with shelf._get(file_url(path, rev)) as r:
        data = r.read()
    if size is not None and len(data) != size:
        raise ShelfError("%s: %d bytes, the index lists %d - not installed"
                         % (path, len(data), size))
    got = shelf.blob_id(data)
    if got != git_oid:
        raise ShelfError("%s: blob id %s, expected %s - not installed"
                         % (path, got[:12], git_oid[:12]))
    with open(dest, "wb") as fh:
        fh.write(data)
    return dest


_INDEX = None


def index():
    global _INDEX
    if _INDEX is None:
        if not os.path.isfile(INDEX):
            raise ShelfError("the KiCad components index is missing from this installation")
        with open(INDEX, encoding="utf-8") as fh:
            _INDEX = json.load(fh)
    return _INDEX


def check_key(key):
    if not re.match(r"^[a-z][a-z0-9_]{1,40}$", key or "") or key not in index()["parts"]:
        raise ShelfError("%r is not a KiCad component" % (key,))
    return key


def label(key):
    return (index()["parts"].get(key) or {}).get("display_name") or key


def search(query="", group=None, limit=500):
    words = [w for w in re.split(r"\W+", (query or "").lower()) if w]
    order = [g for g, _ in GROUPS]
    out = []
    for key, e in index()["parts"].items():
        if group and e.get("group") != group:
            continue
        hay = " ".join((key.replace("_", " "), e.get("display_name", ""),
                        e.get("description", ""), e.get("group", ""),
                        os.path.basename(e.get("path", "")))).lower()
        if any(w not in hay for w in words):
            continue
        out.append((key, e))
    out.sort(key=lambda kv: (order.index(kv[1]["group"]) if kv[1].get("group") in order
                             else 99, kv[1].get("display_name", kv[0]).lower()))
    return out[:limit]


def attribution(entry):
    who = ", ".join(entry.get("authors") or []) or "the KiCad library contributors"
    return '"%s" (%s) by %s, from %s, %s' % (
        entry.get("display_name"), os.path.basename(entry.get("path", "")), who,
        SOURCE, LICENCE)


def part_name(key):
    return PREFIX + key


def install(key, progress=None, freecadcmd=None, replace=False):
    """Download, check, mesh and file component `key` as a user part.
    Returns (part name, user_parts entry)."""
    import user_parts
    check_key(key)
    e = index()["parts"][key]
    rev = index()["revision"]
    name = part_name(key)
    if name in user_parts.specs() and not replace:
        return name, user_parts.specs()[name]
    tmp = tempfile.mkdtemp(prefix="kicad3d_")
    try:
        if progress:
            progress("Downloading %s (%.1f MB)" % (e["display_name"], e["bytes"] / 1e6), None)
        step = fetch(e["path"], e["git_oid"], e["bytes"], os.path.join(tmp, key + ".step"), rev)
        if progress:
            progress("Meshing %s" % e["display_name"], None)
        stl = os.path.join(tmp, name + ".stl")
        rep = shelf.tessellate(step, stl, freecadcmd)
        sp = user_parts.import_part(
            stl, name=name, display_name=e["display_name"],
            category=e["category"], description=e.get("description", ""),
            agent_notes=e.get("agent_notes", ""),
            electrical=e.get("electrical") or None,
            licence=LICENCE, source_url=page_url(e["path"], rev),
            recentre=True, replace=replace,
            extra={"kicad3d": {"key": key, "path": e["path"], "revision": rev,
                               "git_oid": e["git_oid"], "authors": e.get("authors") or [],
                               "attribution": attribution(e),
                               "triangles": rep.get("triangles")}})
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if progress:
        progress("Installed %s" % sp["display_name"], 1.0)
    return name, sp


def installed():
    import user_parts
    out = {}
    for n, sp in user_parts.specs().items():
        k = (sp.get("kicad3d") or {}).get("key")
        if k:
            out[k] = n
    return out


def has_picture(entry):
    return bool(entry.get("picture"))


def thumbnail(key, dest_dir=None):
    """The picture shipped with Prompt2Product (drawn from the mesh), or None."""
    check_key(key)
    e = index()["parts"][key]
    if not e.get("picture"):
        return None
    p = os.path.realpath(os.path.join(HERE, e["picture"]))
    if p.startswith(os.path.join(HERE, "kicad3d_pictures") + os.sep) and os.path.isfile(p):
        return p
    return None
